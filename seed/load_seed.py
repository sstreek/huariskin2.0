"""
Generates SQL INSERT statements from the seed JSON files and writes them to
seed/seed_data.sql. Then you run:

    wrangler d1 execute huariskin --file=seed/seed_data.sql

Run this script with: python seed/load_seed.py
"""

import json
from pathlib import Path

SEED_DIR = Path(__file__).parent
OUT_FILE = SEED_DIR / "seed_data.sql"

lines = ["-- Auto-generated by load_seed.py — do not edit by hand\n"]


def q(value):
    """Wrap a string in single quotes, escaping any internal single quotes."""
    if value is None:
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


# ── ingredients.json ──────────────────────────────────────────────────────────
with open(SEED_DIR / "ingredients.json") as f:
    data = json.load(f)

lines.append("-- Ingredients")
ingredient_id_map = {}  # canonical_name → id (1-indexed for this script)
for i, ing in enumerate(data["ingredients"], start=1):
    ingredient_id_map[ing["canonical_name"]] = i
    lines.append(
        f"INSERT INTO ingredients (id, canonical_name) VALUES ({i}, {q(ing['canonical_name'])});"
    )

lines.append("\n-- Ingredient aliases")
alias_id = 1
for ing in data["ingredients"]:
    ing_id = ingredient_id_map[ing["canonical_name"]]
    for alias in ing.get("aliases", []):
        lines.append(
            f"INSERT INTO ingredient_aliases (id, alias, ingredient_id) VALUES ({alias_id}, {q(alias)}, {ing_id});"
        )
        alias_id += 1


# ── rules.json ────────────────────────────────────────────────────────────────
with open(SEED_DIR / "rules.json") as f:
    data = json.load(f)

lines.append("\n-- Active classes")
class_id_map = {}
for i, cls in enumerate(data["active_classes"], start=1):
    class_id_map[cls["name"]] = i
    lines.append(
        f"INSERT INTO active_classes (id, name, description) VALUES ({i}, {q(cls['name'])}, {q(cls['description'])});"
    )

lines.append("\n-- Ingredient → class mappings")
for ing_name, ing_id in ingredient_id_map.items():
    # Look up this ingredient's classes in ingredients.json
    pass  # TODO: wire ingredient_classes from ingredients.json "classes" field

lines.append("\n-- Conflict rules")
for i, rule in enumerate(data["conflict_rules"], start=1):
    a = class_id_map[rule["class_a"]]
    b = class_id_map[rule["class_b"]]
    lines.append(
        f"INSERT INTO conflict_rules (id, class_a_id, class_b_id, rule_type, reason, citation) "
        f"VALUES ({i}, {a}, {b}, {q(rule['rule_type'])}, {q(rule['reason'])}, {q(rule['citation'])});"
    )

lines.append("\n-- Timing rules")
for i, rule in enumerate(data["timing_rules"], start=1):
    cls_id = class_id_map[rule["class"]]
    lines.append(
        f"INSERT INTO timing_rules (id, class_id, allowed_time) VALUES ({i}, {cls_id}, {q(rule['allowed_time'])});"
    )

lines.append("\n-- Step order")
for i, step in enumerate(data["step_order"], start=1):
    lines.append(
        f"INSERT INTO step_order (id, product_type, order_index) VALUES ({i}, {q(step['product_type'])}, {step['order_index']});"
    )

# ── Write output ──────────────────────────────────────────────────────────────
OUT_FILE.write_text("\n".join(lines))
print(f"Wrote {len(lines)} lines to {OUT_FILE}")
print("Next: wrangler d1 execute huariskin --file=seed/seed_data.sql")
